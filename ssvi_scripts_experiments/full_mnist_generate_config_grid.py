"""
Generate the full-size MNIST / FashionMNIST OOD configs (official 60k/10k split, seeds 0-4).

Each config is the paper's seed-0 config with only the data size, split, seed and
logging cadence changed, so every training hyperparameter stays as in the paper.

Usage (from ssvi_scripts_experiments/):
    python full_mnist_generate_config_grid.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).parent / "ood_mnist_related"

# output folder -> (paper folder, extra overrides) per dataset and arm
SOURCES = {
    "full_mnist_v1_ssvi": ("reverse_mnist_ood_experiment_final_v3_ssvi", {}),
    "full_mnist_v1_orig_gplvm": ("reverse_mnist_ood_experiment_final_v3_orig_gplvm", {}),
    "full_fmnist_v1_ssvi": ("fashion_mnist_ood_experiment_final_v2_ssvi", {}),
    "full_fmnist_v1_orig_gplvm": ("fashion_mnist_ood_experiment_final_v2_orig_gplvm", {}),
}
SEEDS = [0, 1, 2, 3, 4]

# Metrics and checkpoint plots pass over all 70k ID images; every 20k steps instead of 4k
OVERRIDES = {
    "id_samples_per_class": "null",
    "use_official_split": "true",
    "checkpoint_frequency": "20000",
    "metrics_frequency": "20000",
}


def set_key(text, key, value):
    """Replace a top-level `key: ...` line, or append it if the paper config lacks it."""
    pattern = re.compile(rf"^{key}:.*$", re.MULTILINE)
    line = f"{key}: {value}"
    if pattern.search(text):
        return pattern.sub(line, text, count=1)
    return text.rstrip("\n") + f"\n{line}\n"


def main():
    for out_name, (src_name, extra) in SOURCES.items():
        (base,) = sorted((ROOT / src_name).glob("*_s_0_*.yaml"))
        text = base.read_text()
        out_dir = ROOT / out_name
        out_dir.mkdir(exist_ok=True)
        for seed in SEEDS:
            config = text
            for key, value in {**OVERRIDES, **extra, "random_seed": str(seed)}.items():
                config = set_key(config, key, value)
            header = f"# Generated by full_mnist_generate_config_grid.py from {src_name}/{base.name}\n"
            out_path = out_dir / base.name.replace("_s_0_", f"_s_{seed}_")
            out_path.write_text(header + config)
            print(f"wrote {out_path.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
